CREATE TABLE staff_roles (
  role_key text PRIMARY KEY CHECK (role_key ~ '^[a-z][a-z0-9_]{1,47}$'),
  display_name text NOT NULL CHECK (display_name <> ''),
  role_kind text NOT NULL CHECK (role_kind IN ('player', 'staff', 'world')),
  hierarchy_level smallint CHECK (hierarchy_level BETWEEN 0 AND 5),
  is_staff boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((role_kind = 'staff') = is_staff)
);

CREATE TABLE staff_permission_catalog (
  permission_key text PRIMARY KEY CHECK (permission_key <> ''),
  domain text NOT NULL CHECK (domain <> ''),
  description text NOT NULL CHECK (description <> ''),
  assignable boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE staff_role_inheritance (
  role_key text NOT NULL REFERENCES staff_roles(role_key) ON DELETE RESTRICT,
  inherits_role_key text NOT NULL REFERENCES staff_roles(role_key) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (role_key, inherits_role_key),
  CHECK (role_key <> inherits_role_key)
);

CREATE TABLE staff_role_permissions (
  role_key text NOT NULL REFERENCES staff_roles(role_key) ON DELETE RESTRICT,
  permission_key text NOT NULL REFERENCES staff_permission_catalog(permission_key) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (role_key, permission_key)
);

CREATE TABLE account_role_assignments (
  assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id uuid NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
  role_key text NOT NULL REFERENCES staff_roles(role_key) ON DELETE RESTRICT,
  scope_key text NOT NULL DEFAULT 'global' CHECK (scope_key <> ''),
  assigned_by_account_id uuid REFERENCES accounts(id) ON DELETE SET NULL,
  reason text NOT NULL CHECK (reason <> ''),
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz,
  revoked_at timestamptz,
  CHECK (expires_at IS NULL OR expires_at > created_at)
);

CREATE UNIQUE INDEX account_role_assignments_active_idx
  ON account_role_assignments (account_id, role_key, scope_key)
  WHERE revoked_at IS NULL;
CREATE INDEX account_role_assignments_account_idx
  ON account_role_assignments (account_id, scope_key)
  WHERE revoked_at IS NULL;

CREATE TABLE staff_audit_events (
  event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_account_id uuid REFERENCES accounts(id) ON DELETE SET NULL,
  target_account_id uuid REFERENCES accounts(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (action <> ''),
  scope_key text NOT NULL DEFAULT 'global' CHECK (scope_key <> ''),
  reason text NOT NULL CHECK (reason <> ''),
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
  happened_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX staff_audit_actor_time_idx
  ON staff_audit_events (actor_account_id, happened_at DESC);
CREATE INDEX staff_audit_target_time_idx
  ON staff_audit_events (target_account_id, happened_at DESC);
CREATE INDEX staff_audit_action_time_idx
  ON staff_audit_events (action, happened_at DESC);

