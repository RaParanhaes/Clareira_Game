CREATE TABLE player_reports (
  report_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_account_id uuid REFERENCES accounts(id) ON DELETE SET NULL,
  target_account_id uuid NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
  category text NOT NULL CHECK (category IN ('harassment','cheating','exploit','impersonation','other')),
  description text NOT NULL CHECK (char_length(btrim(description)) BETWEEN 10 AND 1200),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','claimed','resolved','dismissed')),
  assigned_to_account_id uuid REFERENCES accounts(id) ON DELETE SET NULL,
  scope_key text NOT NULL DEFAULT 'global' CHECK (scope_key <> ''),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (reporter_account_id IS NULL OR reporter_account_id <> target_account_id),
  CHECK ((status = 'claimed') = (assigned_to_account_id IS NOT NULL))
);
CREATE INDEX player_reports_queue_idx ON player_reports(status, created_at DESC, report_id DESC);
CREATE INDEX player_reports_assignee_idx ON player_reports(assigned_to_account_id, status, created_at DESC);
CREATE INDEX player_reports_target_idx ON player_reports(target_account_id, created_at DESC);

CREATE TABLE player_sanctions (
  sanction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_account_id uuid NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
  kind text NOT NULL CHECK (kind IN ('warning','mute','kick','suspend','ban')),
  reason text NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 1 AND 500),
  created_by_account_id uuid REFERENCES accounts(id) ON DELETE SET NULL,
  related_report_id bigint REFERENCES player_reports(report_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz,
  lifted_at timestamptz,
  lifted_by_account_id uuid REFERENCES accounts(id) ON DELETE SET NULL,
  lift_reason text CHECK (lift_reason IS NULL OR char_length(btrim(lift_reason)) BETWEEN 1 AND 500),
  CHECK ((lifted_at IS NULL) = (lift_reason IS NULL)),
  CHECK (kind NOT IN ('warning','ban') OR expires_at IS NULL),
  CHECK (kind NOT IN ('mute','suspend') OR expires_at IS NOT NULL),
  CHECK (expires_at IS NULL OR expires_at > created_at)
);
CREATE INDEX player_sanctions_active_target_idx
  ON player_sanctions(target_account_id, kind, expires_at)
  WHERE lifted_at IS NULL;
CREATE INDEX player_sanctions_created_idx ON player_sanctions(created_at DESC, sanction_id DESC);

CREATE OR REPLACE FUNCTION public.staff_submit_report_from_session(
  p_session_hash bytea,
  p_target_account_id uuid,
  p_category text,
  p_description text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  reporter_id uuid;
  new_report_id bigint;
BEGIN
  reporter_id := public.staff_session_account_id(p_session_hash);
  IF reporter_id IS NULL OR p_target_account_id IS NULL
     OR p_category NOT IN ('harassment','cheating','exploit','impersonation','other')
     OR p_description IS NULL OR char_length(btrim(p_description)) NOT BETWEEN 10 AND 1200
     OR reporter_id = p_target_account_id
     OR NOT EXISTS (SELECT 1 FROM public.accounts WHERE id = p_target_account_id) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Dados da denúncia inválidos.';
  END IF;

  INSERT INTO public.player_reports (reporter_account_id, target_account_id, category, description)
  VALUES (reporter_id, p_target_account_id, p_category, btrim(p_description))
  RETURNING report_id INTO new_report_id;
  INSERT INTO public.staff_audit_events (actor_account_id, target_account_id, action, scope_key, reason, details)
  VALUES (reporter_id, p_target_account_id, 'player.report.submitted', 'global', 'Denúncia enviada pelo jogador',
    jsonb_build_object('report_id', new_report_id, 'category', p_category));
  RETURN new_report_id;
END
$$;

CREATE OR REPLACE FUNCTION public.staff_update_report_from_session(
  p_session_hash bytea,
  p_report_id bigint,
  p_action text,
  p_reason text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  actor_id uuid;
  report_row public.player_reports%ROWTYPE;
  is_owner boolean;
BEGIN
  actor_id := public.staff_session_account_id(p_session_hash);
  IF actor_id IS NULL OR NOT public.staff_actor_has_permission(actor_id, 'reports.manage', 'global')
     OR p_report_id IS NULL OR p_action NOT IN ('claim','resolve','dismiss','reopen')
     OR p_reason IS NULL OR char_length(btrim(p_reason)) NOT BETWEEN 1 AND 500 THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Permissão ou dados da denúncia inválidos.';
  END IF;
  SELECT * INTO report_row FROM public.player_reports WHERE report_id = p_report_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Denúncia não encontrada.'; END IF;
  is_owner := public.staff_actor_has_permission(actor_id, '*', report_row.scope_key);
  IF report_row.assigned_to_account_id IS NOT NULL AND report_row.assigned_to_account_id <> actor_id AND NOT is_owner THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'A denúncia está atribuída a outro moderador.';
  END IF;

  IF p_action = 'claim' AND report_row.status = 'open' THEN
    UPDATE public.player_reports SET status = 'claimed', assigned_to_account_id = actor_id, updated_at = now()
      WHERE report_id = p_report_id;
  ELSIF p_action = 'resolve' AND report_row.status = 'claimed' THEN
    UPDATE public.player_reports SET status = 'resolved', assigned_to_account_id = NULL, updated_at = now()
      WHERE report_id = p_report_id;
  ELSIF p_action = 'dismiss' AND report_row.status IN ('open','claimed') THEN
    UPDATE public.player_reports SET status = 'dismissed', assigned_to_account_id = NULL, updated_at = now()
      WHERE report_id = p_report_id;
  ELSIF p_action = 'reopen' AND report_row.status IN ('resolved','dismissed') THEN
    UPDATE public.player_reports SET status = 'open', assigned_to_account_id = NULL, updated_at = now()
      WHERE report_id = p_report_id;
  ELSE
    RETURN false;
  END IF;

  INSERT INTO public.staff_audit_events (actor_account_id, target_account_id, action, scope_key, reason, details)
  VALUES (actor_id, report_row.target_account_id, 'player.report.' || p_action, report_row.scope_key,
    btrim(p_reason), jsonb_build_object('report_id', p_report_id, 'previous_status', report_row.status));
  RETURN true;
END
$$;

CREATE OR REPLACE FUNCTION public.staff_apply_sanction_from_session(
  p_session_hash bytea,
  p_target_account_id uuid,
  p_kind text,
  p_expires_at timestamptz,
  p_reason text,
  p_report_id bigint DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  actor_id uuid;
  permission_key text;
  actor_level smallint;
  target_level smallint;
  is_owner boolean;
  new_sanction_id bigint;
BEGIN
  actor_id := public.staff_session_account_id(p_session_hash);
  permission_key := CASE p_kind
    WHEN 'warning' THEN 'players.warn'
    WHEN 'mute' THEN 'players.mute'
    WHEN 'kick' THEN 'players.kick'
    WHEN 'suspend' THEN 'players.suspend'
    WHEN 'ban' THEN 'players.ban.permanent'
    ELSE NULL END;
  IF actor_id IS NULL OR permission_key IS NULL OR p_target_account_id IS NULL
     OR p_reason IS NULL OR char_length(btrim(p_reason)) NOT BETWEEN 1 AND 500
     OR NOT EXISTS (SELECT 1 FROM public.accounts WHERE id = p_target_account_id)
     OR NOT public.staff_actor_has_permission(actor_id, permission_key, 'global') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Permissão ou dados da sanção inválidos.';
  END IF;
  IF (p_kind IN ('mute','suspend') AND (p_expires_at IS NULL OR p_expires_at <= now()))
     OR (p_kind IN ('warning','ban','kick') AND p_expires_at IS NOT NULL) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Prazo da sanção inválido.';
  END IF;
  IF p_report_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.player_reports WHERE report_id = p_report_id) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Denúncia não encontrada.';
  END IF;

  is_owner := public.staff_actor_has_permission(actor_id, '*', 'global');
  actor_level := public.staff_actor_highest_level(actor_id, 'global');
  target_level := public.staff_actor_highest_level(p_target_account_id, 'global');
  IF (actor_id = p_target_account_id AND NOT is_owner) OR (NOT is_owner AND target_level IS NOT NULL
      AND (actor_level IS NULL OR actor_level <= target_level)) THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Não é possível aplicar sanção nesta conta.';
  END IF;

  INSERT INTO public.player_sanctions (target_account_id, kind, reason, created_by_account_id,
      related_report_id, expires_at)
  VALUES (p_target_account_id, p_kind, btrim(p_reason), actor_id, p_report_id,
      CASE WHEN p_kind = 'kick' THEN now() + interval '30 seconds' ELSE p_expires_at END)
  RETURNING sanction_id INTO new_sanction_id;
  INSERT INTO public.staff_audit_events (actor_account_id, target_account_id, action, scope_key, reason, details)
  VALUES (actor_id, p_target_account_id, 'player.sanction.' || p_kind, 'global', btrim(p_reason),
      jsonb_build_object('sanction_id', new_sanction_id, 'expires_at',
        CASE WHEN p_kind = 'kick' THEN now() + interval '30 seconds' ELSE p_expires_at END,
        'report_id', p_report_id));
  RETURN new_sanction_id;
END
$$;

CREATE OR REPLACE FUNCTION public.staff_revoke_sanction_from_session(
  p_session_hash bytea,
  p_sanction_id bigint,
  p_reason text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  actor_id uuid;
  sanction public.player_sanctions%ROWTYPE;
  permission_key text;
  is_owner boolean;
  actor_level smallint;
  target_level smallint;
BEGIN
  actor_id := public.staff_session_account_id(p_session_hash);
  IF actor_id IS NULL OR p_sanction_id IS NULL OR p_reason IS NULL
     OR char_length(btrim(p_reason)) NOT BETWEEN 1 AND 500 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Dados para remover sanção inválidos.';
  END IF;
  SELECT * INTO sanction FROM public.player_sanctions WHERE sanction_id = p_sanction_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Sanção não encontrada.'; END IF;
  permission_key := CASE sanction.kind
    WHEN 'warning' THEN 'players.warn' WHEN 'mute' THEN 'players.mute'
    WHEN 'kick' THEN 'players.kick' WHEN 'suspend' THEN 'players.suspend'
    WHEN 'ban' THEN 'players.ban.permanent' END;
  is_owner := public.staff_actor_has_permission(actor_id, '*', 'global');
  actor_level := public.staff_actor_highest_level(actor_id, 'global');
  target_level := public.staff_actor_highest_level(sanction.target_account_id, 'global');
  IF NOT is_owner AND (NOT public.staff_actor_has_permission(actor_id, 'players.sanction.revoke', 'global')
      OR NOT public.staff_actor_has_permission(actor_id, permission_key, 'global')
      OR (target_level IS NOT NULL AND (actor_level IS NULL OR actor_level <= target_level))) THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Você não pode remover esta sanção.';
  END IF;
  IF sanction.lifted_at IS NOT NULL THEN RETURN false; END IF;
  UPDATE public.player_sanctions SET lifted_at = now(), lifted_by_account_id = actor_id, lift_reason = btrim(p_reason)
    WHERE sanction_id = p_sanction_id;
  INSERT INTO public.staff_audit_events (actor_account_id, target_account_id, action, scope_key, reason, details)
  VALUES (actor_id, sanction.target_account_id, 'player.sanction.revoked', 'global', btrim(p_reason),
      jsonb_build_object('sanction_id', p_sanction_id, 'kind', sanction.kind));
  RETURN true;
END
$$;

